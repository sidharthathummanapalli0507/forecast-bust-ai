/**
 * Generate 24-hour realistic hourly telemetry for a given station
 * for plotting in the interactive meteogram chart.
 */
function generateStation24hMeteogram(station) {
  const hours = [];
  const rainProfile = [];
  const tempProfile = [];
  const pressProfile = [];
  const windProfile = [];

  const now = new Date();
  
  for (let i = 23; i >= 0; i--) {
    const t = new Date(now.getTime() - i * 3600 * 1000);
    const hourLabel = t.getHours().toString().padStart(2, '0') + ':00';
    hours.push(hourLabel);

    // Diurnal temperature cycle
    const hour = t.getHours();
    const diurnalFactor = Math.sin((hour - 9) * (Math.PI / 12));
    const hourlyTemp = Number((station.temp + diurnalFactor * 3.5 + (Math.random() * 0.6 - 0.3)).toFixed(1));
    tempProfile.push(hourlyTemp);

    // Rainfall distribution weighted towards recent convective afternoon/evening hours
    let hRain = 0;
    if (station.rain24h > 0) {
      if (i < 4) {
        hRain = (station.rain1h * (0.8 + Math.random() * 0.4)).toFixed(1);
      } else if (i < 10) {
        hRain = ((station.rain3h / 3) * (0.6 + Math.random() * 0.8)).toFixed(1);
      } else {
        hRain = (Math.max(0, (station.rain24h / 24) * (0.3 + Math.random() * 0.9))).toFixed(1);
      }
    }
    rainProfile.push(Number(hRain));

    // Pressure profile with semi-diurnal atmospheric tidal wave
    const tide = Math.cos((hour - 10) * (Math.PI / 6)) * 1.5;
    pressProfile.push(Number((station.pressure + tide + (Math.random() * 0.3 - 0.15)).toFixed(1)));

    // Wind speed fluctuation
    windProfile.push(Number(Math.max(2, (station.windSpeed + (Math.random() * 8 - 4))).toFixed(1)));
  }

  return {
    hours,
    rainProfile,
    tempProfile,
    pressProfile,
    windProfile
  };
}

